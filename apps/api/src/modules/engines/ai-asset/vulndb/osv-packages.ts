const PYPI_SET = new Set(Object.values(OSV_PYPI_PACKAGES).flat().map(normalizePypiName));
const NPM_SET = new Set(OSV_NPM_PACKAGES);

export function acceptPypi(name: string): boolean {
  const n = normalizePypiName(name);
  return PYPI_SET.has(n) || OSV_PYPI_PREFIXES.some((p) => n.startsWith(p));
}

export function acceptNpm(name: string): boolean {
  return NPM_SET.has(name.trim());
}
